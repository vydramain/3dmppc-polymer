// U+0410..U+044F in code order, then U+0401 and U+0451.
inline constexpr int rv_font_cyrillic_glyph_count = 66;

// Slot of a code point inside this block, or -1 when the block has no glyph for it.
inline constexpr int rv_font_cyrillic_slot(char32_t code)
{
    if (code >= 0x0410 && code <= 0x044F) {
        return static_cast<int>(code - 0x0410);
    }
    if (code == 0x0401) {
        return 64;
    }
    if (code == 0x0451) {
        return 65;
    }
    return -1;
}

