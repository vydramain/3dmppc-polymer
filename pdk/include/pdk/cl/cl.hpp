// Controller Lua — виртуальная машина консоли. Аксессор: rv_pdko::cl().
//
// TODO(2). Напиши сюда шапку в стиле соседей (rv_cd.hpp, rv_cm.hpp): что это
//   за железо, кто им владеет, какая конвенция ошибок. Три вещи, которые в этой
//   шапке обязаны быть сказаны:
//     * VM включена всегда, диску не надо её просить или инициализировать —
//       ровно как растеризатор существует, даже если диск ничего не рисует;
//     * чанк адресуется по HANDLE, который выдаёт script_load (та же схема
//       «имя -> handle», что у rv_cd::asset_open);
//     * ошибка внутри скрипта — это НЕ падение консоли, а отрицательный rv_err.
class rv_cl
{
public:
	virtual ~rv_cl() = default;

	// ── Группа A: жизненный цикл чанка ────────────────────────────────────────
	//
	// TODO(3). script_load(const void *bytecode, int64_t size, const char *name)
	//   Принимает БАЙТКОД (не текст), возвращает handle чанка (>= 0).
	//
	//   `name` — только для сообщений об ошибках («disc:12: attempt to ...»),
	//   на исполнение не влияет. Строку скопируй: диск не обязан её хранить.
	//
	//   Что делает реализация, по шагам:
	//     1. luaL_loadbuffer — байткод превращается в функцию на стеке Lua;
	//     2. lua_pcall этой функции — ОБЯЗАТЕЛЬНО. Тело чанка не «загружается»,
	//        оно ИСПОЛНЯЕТСЯ, и только в этот момент появляются глобалы
	//        frame_update / frame_render. Без шага 2 звать будет нечего;
	//     3. запомнить чанк и вернуть handle.
	//
	//   Коды ошибок, которые тут нужны:
	//     RV_ERR_INVAL — bytecode == nullptr, size <= 0, или это не байткод
	//                    (первые байты валидного чанка — 0x1B 'L' 'J');
	//     RV_ERR_NOMEM — таблица чанков переполнена;
	//     RV_ERR_IO    — байткод битый, или тело чанка бросило error().
	//
	// TODO(4). script_free(int64_t chunk)
	//   Отпустить чанк. Держать его вечно нельзя: пока на функцию есть ссылка,
	//   сборщик мусора Lua не тронет ни её, ни всё, что она замкнула.

	// ── Группа B: положить аргументы ──────────────────────────────────────────
	//
	// TODO(5). Методы stack_push_*: number(double), integer(int64_t),
	//   boolean(bool), string(const char *, int64_t len), nil().
	//   Возвращают RV_OK или RV_ERR_NOMEM (стек Lua не резиновый, его глубину
	//   реализация обязана проверять через lua_checkstack).
	//
	//   Плюс два служебных: stack_drop(int64_t count) — снять со стека, и
	//   stack_count() — сколько сейчас лежит. Второй нужен для отладки: в конце
	//   кадра он ОБЯЗАН показывать то же, что в начале.

	// ── Группа C: прочитать результаты ────────────────────────────────────────
	//
	// TODO(6). value_type(int64_t index) -> rv_cl_type
	//   Диск сначала спрашивает тип, потом читает соответствующим методом.
	//
	//   `index` — как в самой Lua: 1 — дно стека, -1 — вершина. Отрицательный
	//   индекс удобнее: -1 всегда «то, что вернули последним», независимо от
	//   того, сколько всего лежит.
	//
	// TODO(7). value_number(int64_t index, double *out) и родня.
	//   Возврат — статус (RV_OK / RV_ERR_INVAL при неверном индексе или чужом
	//   типе), значение — в *out. Вот тут и работает ответ на вопрос 2.
	//
	//   value_string отдельный случай: пусть принимает буфер диска
	//   (char *buf, int64_t cap) и возвращает число записанных байт, как
	//   rv_cd::asset_read. Возвращать const char* из VM нельзя — сборщик мусора
	//   заберёт строку сразу после stack_drop, и у диска останется висячий
	//   указатель.

	// ── Группа D: вызов ───────────────────────────────────────────────────────
	//
	// TODO(8). script_call(int64_t chunk, const char *fname, int64_t argc, int64_t retc)
	//   Позвать глобальную функцию `fname` из чанка. argc аргументов уже лежат
	//   на стеке (положены группой B), retc результатов останутся на стеке для
	//   группы C.
	//
	//   Реализация обязана: (а) использовать lua_pcall, НЕ lua_call — lua_call
	//   при ошибке делает longjmp мимо C++ кода, деструкторы не отработают;
	//   (б) при ошибке вернуть RV_ERR_IO, оставив текст ошибки на вершине стека,
	//   чтобы диск прочитал его через value_string; (в) вернуть стек в исходное
	//   состояние на ЛЮБОМ пути выхода, включая ошибочный.
};

